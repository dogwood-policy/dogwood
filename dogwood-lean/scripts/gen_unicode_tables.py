def inside(ranges, x):
    lo, hi = 0, len(ranges)
    while lo < hi:
        mid = (lo + hi) // 2
        if ranges[mid][1] <= x:
            lo = mid + 1
        else:
            hi = mid
    return lo < len(ranges) and ranges[lo][0] <= x


def lean_array(name, doc, ranges):
    bounds = [b for r in ranges for b in r]
    lines = []
    for i in range(0, len(bounds), 8):
        lines.append("  " + ", ".join(f"0x{b:x}" for b in bounds[i:i + 8]))
    return (f"/-- {doc} -/\n"
            f"def {name} : Array Nat := #[\n" + ",\n".join(lines) + "]\n")


def sources(src):
    """The source files the tables are decoded from, by their names in the header: up to Rust
    1.96 `printable.rs`, since 1.97 `char/methods.rs`; and `unicode_data.rs`."""
    out = {}
    if os.path.isfile(os.path.join(src, "printable.rs")):
        out["printable.rs"] = read(os.path.join(src, "printable.rs"))
    else:
        out["char/methods.rs"] = read(os.path.join(src, "..", "char", "methods.rs"))
    out["unicode_data.rs"] = read(os.path.join(src, "unicode_data.rs"))
    return out


def generate(version, src):
    files = sources(src)
    data_src = files["unicode_data.rs"]
    unicode = re.search(r"UNICODE_VERSION: \(u8, u8, u8\) = \((\d+), (\d+), (\d+)\)", data_src)
    if not unicode:
        sys.exit("error: no UNICODE_VERSION in unicode_data.rs")
    if "printable.rs" in files:
        np = non_printable(files["printable.rs"])
        np_doc = ("The code points `core::unicode::printable::is_printable` rejects, the ASCII "
                  "ones included (below `0x20`, and `0x7f`).")
    else:
        np = non_printable_since_1_97(files["char/methods.rs"], data_src)
        np_doc = ("The code points `char::escape_debug_ext` writes as `\\u{…}` whatever its "
                  "arguments: the controls, private-use characters, whitespace, "
                  "default-ignorable code points, format controls and unassigned code points; "
                  "the ASCII ones included (below `0x20`, and `0x7f`).")
    ge = grapheme_extend(data_src)
    ge_doc = ("The code points with Unicode's `Grapheme_Extend` property, as "
              "`core::unicode::unicode_data::grapheme_extend::lookup` decides it (none below "
              "`0x300`).")
    if "char/methods.rs" in files:
        fast = escape_debug_ext(files["char/methods.rs"])
        if fast:
            # The fast path comes before the test of a grapheme extender.
            ge = subtract(ge, fast)
            ge_doc = ("The grapheme extenders `char::escape_debug_ext` escapes when asked: the "
                      "code points with Unicode's `Grapheme_Extend` property, as "
                      "`core::unicode::unicode_data::grapheme_extend::lookup` decides it (none "
                      "below `0x300`), but not those of its fast path ("
                      + ", ".join(f"`U+{x:04X}`" for lo, hi in fast for x in range(lo, hi))
                      + ").")
    digest = lambda s: hashlib.sha256(s.encode("utf-8")).hexdigest()
    listed = ",\n".join(f"`{name}` {digest(text)}" for name, text in files.items())
    text = f"""/-!
# The Unicode tables of Rust's `escape_debug`

Generated by `scripts/gen_unicode_tables.py` from the sources of `{version}`
(`library/core/src/`, Unicode {".".join(unicode.groups())}); do not edit. SHA-256 of the sources:
{listed}.

Each table is the sorted boundaries `b₀ < b₁ < …` of half-open code point ranges
`[b₀, b₁), [b₂, b₃), …`: a code point is in the table when an odd number of boundaries are at
most it (`Dogwood.Frontend.Escape.inTable`).
-/

namespace Dogwood.Frontend.UnicodeTables

/-- The Rust release the tables come from. -/
def rustVersion : String := "{RUST_VERSION}"

/-- The Unicode version of the tables (`core::char::UNICODE_VERSION`). -/
def unicodeVersion : String := "{".".join(unicode.groups())}"

{lean_array("notPrintable", np_doc, np)}
{lean_array("graphemeExtend", ge_doc, ge)}
end Dogwood.Frontend.UnicodeTables
"""
    return text, np, ge, files


def self_test(np, ge, files):
    if "printable.rs" not in files:
        self_test_since_1_97(np, ge, files)
        return
    printable_src, data_src = files["printable.rs"], files["unicode_data.rs"]
    uppers0 = ints(array_body(printable_src, "SINGLETONS0U"))
    uppers1 = ints(array_body(printable_src, "SINGLETONS1U"))
    tables = [
        (list(zip(uppers0[0::2], uppers0[1::2])), ints(array_body(printable_src, "SINGLETONS0L")),
         ints(array_body(printable_src, "NORMAL0"))),
        (list(zip(uppers1[0::2], uppers1[1::2])), ints(array_body(printable_src, "SINGLETONS1L")),
         ints(array_body(printable_src, "NORMAL1"))),
    ]
    tail = is_printable_tail(printable_src)
    headers, offsets = grapheme_module(data_src)
    bad = 0
    for x in range(MAX_CHAR):
        if 0xD800 <= x < 0xE000:
            continue
        if x < 32:
            printable = False
        elif x < 127:
            printable = True
        elif x < 0x20000:
            printable = check_literal(x & 0xFFFF, *tables[x >> 16])
        else:
            printable = not any(lo <= x < hi for lo, hi in tail)
        extend = x >= 0x300 and skip_search_literal(x, headers, offsets)
        if printable == inside(np, x) or extend != inside(ge, x):
            bad += 1
            if bad <= 10:
                print(f"self-test: U+{x:04X}: printable {printable}, extend {extend}",
                      file=sys.stderr)
    if bad:
        sys.exit(f"error: the decoded tables differ from the sources' lookups on {bad} code points")
    print("self-test: the decoded tables agree with the sources' lookups on every scalar value")

def self_test_since_1_97(np, ge, files):
    """Since Rust 1.97: every skip list's `skip_search` and `white_space::lookup`, ported
    literally, against the decoded tables, on every scalar value."""
    data = files["unicode_data.rs"]
    lists = {name: skiplist_module(data, name, guard) for name, guard in
             [("default_ignorable_code_point", 0xAD), ("cf", 0xAD), ("cn_planes_0_3", 0x378),
              ("grapheme_extend", 0x300)]}
    module = re.search(r"pub mod white_space \{(.*?)\n\}", data, re.S).group(1)
    wmap = ints(array_body(module, "WHITESPACE_MAP"))
    assigned = normalize(char_ranges(fn_body(files["char/methods.rs"],
                                             "pub fn is_assigned(self) -> bool")
                                     .split("!unicode::Cn_planes_0_3(self),", 1)[1]
                                     .split("=> true")[0]))
    private = char_ranges(fn_body(files["char/methods.rs"],
                                  "pub const fn is_private_use(self) -> bool"))
    fast = escape_debug_ext(files["char/methods.rs"])

    def lookup(name, x):
        headers, offsets = lists[name]
        return skip_search_literal(x, headers, offsets)

    def whitespace(x):
        if x in (0x20,) or 0x09 <= x <= 0x0D:
            return True
        if x <= 0x84:
            return False
        hi = x >> 8
        return (hi == 0 and wmap[x & 0xFF] & 1 != 0) or (hi == 22 and x == 0x1680) or \
            (hi == 32 and wmap[x & 0xFF] & 2 != 0) or (hi == 48 and x == 0x3000)

    bad = 0
    for x in range(MAX_CHAR):
        if 0xD800 <= x < 0xE000:
            continue
        if x <= 0x377:
            is_assigned = True
        elif x <= 0x3FFFD:
            is_assigned = not lookup("cn_planes_0_3", x)
        else:
            is_assigned = any(lo <= x < hi for lo, hi in assigned)
        in_fast = any(lo <= x < hi for lo, hi in fast)
        escaped = not 0x20 <= x <= 0x7E and not in_fast and (
                   x < 0x20 or 0x7F <= x <= 0x9F or any(lo <= x < hi for lo, hi in private)
                   or whitespace(x) or (x > 0xAC and lookup("default_ignorable_code_point", x))
                   or (x > 0xAC and lookup("cf", x)) or not is_assigned)
        extend = not in_fast and x > 0x2FF and lookup("grapheme_extend", x)
        if escaped != inside(np, x) or extend != inside(ge, x):
            bad += 1
            if bad <= 10:
                print(f"self-test: U+{x:04X}: escaped {escaped}, extend {extend}",
                      file=sys.stderr)
    if bad:
        sys.exit(f"error: the decoded tables differ from the sources' lookups on {bad} code points")
    print("self-test: the decoded tables agree with the sources' lookups on every scalar value")


RUST_PROBE = r"""
fn main() {
    // For every scalar value: whether `char::escape_debug` escapes it as `\u{…}` (it is
    // not printable or extends a grapheme), and whether a string's `escape_debug` does
    // after its first character (it is not printable).
    let mut out = String::new();
    for x in 0..0x110000u32 {
        let Some(c) = char::from_u32(x) else { continue };
        let all = c.escape_debug().to_string().starts_with("\\u{");
        let rest = format!("a{c}").escape_debug().to_string()[1..].starts_with("\\u{");
        let quoted = format!("{:?}", c.to_string());
        let debug = quoted[1..quoted.len() - 1].starts_with("\\u{");
        out.push_str(&format!("{x:x} {} {} {}\n", all as u8, rest as u8, debug as u8));
    }
    print!("{out}");
}
"""


def verify_with_rust(np, ge, env=None):
    with tempfile.TemporaryDirectory() as tmp:
        probe = os.path.join(tmp, "probe.rs")
        exe = os.path.join(tmp, "probe")
        with open(probe, "w") as f:
            f.write(RUST_PROBE)
        subprocess.run(["rustc", "-O", "-o", exe, probe], check=True, env=env)
        out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    bad = 0
    count = 0
    for line in out.splitlines():
        x, all_, rest, debug = line.split()
        x = int(x, 16)
        count += 1
        # Characters with their own escapes are never `\u{…}`.
        special = x in (0, 9, 10, 13, 0x22, 0x27, 0x5C)
        exp_rest = not special and inside(np, x)
        exp_all = not special and (inside(np, x) or inside(ge, x))
        if (all_ == "1") != exp_all or (rest == "1") != exp_rest or (debug == "1") != exp_all:
            bad += 1
            if bad <= 10:
                print(f"verify: U+{x:04X}: Rust {all_} {rest} {debug}", file=sys.stderr)
    if count != MAX_CHAR - 0x800:
        sys.exit(f"error: the Rust probe printed {count} scalar values")
    if bad:
        sys.exit(f"error: the tables differ from the toolchain's escape_debug on {bad} scalar values")
    print(f"verify: the tables agree with the toolchain's escape_debug on all {count} scalar values")


# ── The changes between two releases ─────────────────────────────────────────

# The code points two Rust releases escape differently, which the crate's test of the tables
# (`escaping_agrees_at_every_boundary_of_the_unicode_tables`) leaves out when the crate is
# compiled with one of the releases and the tables come from the other.
CHANGES = os.path.join("..", "dogwood-language", "src", "lean_frontend", "escape_changes.txt")


def escape_class(np, ge, x):
    """How `escape_debug` writes `x` with the tables `np` and `ge`: `u`, as `\\u{…}` wherever it
    is (not printable); `g`, as `\\u{…}` at the start of a string and as itself after another
    character (a grapheme extender); `-`, as itself."""
    return "u" if inside(np, x) else "g" if inside(ge, x) else "-"


def changes(old, new):
    """The half-open ranges of the scalar values that the tables `old` and `new` (each a
    `(np, ge)` pair) escape differently, with the class of each in either."""
    out = []
    for x in range(MAX_CHAR):
        if 0xD800 <= x < 0xE000:
            continue
        a, b = escape_class(*old, x), escape_class(*new, x)
        if a == b:
            continue
        if out and out[-1][1] == x and out[-1][2:] == (a, b):
            out[-1] = (out[-1][0], x + 1, a, b)
        else:
            out.append((x, x + 1, a, b))
    return out


def changes_text(old_version, new_version, ranges):
    release = lambda v: re.match(r"rustc (\S+)", v).group(1)
    lines = [
        "# Generated by `dogwood-lean/scripts/gen_unicode_tables.py --changes` from the sources",
        f"# of `{old_version}` and `{new_version}`; do not edit.",
        "#",
        "# The scalar values the two releases' `escape_debug` writes differently. When the crate is",
        "# compiled with one of the releases and the Lean frontend's Unicode tables come from the",
        "# other, the frontends print these characters differently, and the test",
        "# `escaping_agrees_at_every_boundary_of_the_unicode_tables` leaves them out (and checks",
        "# that the compiler writes each as this file says).",
        "#",
        "# `releases A B`, then one half-open range per line: `lo hi a b` (hexadecimal), with the",
        "# class of its scalar values in A and in B: `u`, written `\\u{…}` wherever it is (not",
        "# printable); `g`, written `\\u{…}` at the start of a string and as itself after another",
        "# character (a grapheme extender); `-`, written as itself.",
        f"releases {release(old_version)} {release(new_version)}",
    ]
    lines += [f"{lo:x} {hi:x} {a} {b}" for lo, hi, a, b in ranges]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the output is not current")
    ap.add_argument("--self-test", action="store_true",
                    help="compare the decoded tables with the sources' lookups, ported")
    ap.add_argument("--verify", action="store_true",
                    help="compare the decoded tables with the toolchain's escape_debug")
    ap.add_argument("--changes", metavar="TOOLCHAIN",
                    help="instead of the tables, write (or with --check, check) "
                         f"{CHANGES}: the scalar values that RUST_VERSION and the rustup "
                         "toolchain TOOLCHAIN escape differently")
    args = ap.parse_args()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    version, src = rust_sources()
    text, np, ge, files = generate(version, src)
    if args.self_test:
        self_test(np, ge, files)
    if args.verify:
        verify_with_rust(np, ge)
    if args.changes:
        other_version, other_src = rust_sources(args.changes, pinned=False)
        _, other_np, other_ge, other_files = generate(other_version, other_src)
        if args.self_test:
            self_test(other_np, other_ge, other_files)
        if args.verify:
            verify_with_rust(other_np, other_ge, toolchain_env(args.changes))
        ranges = changes((np, ge), (other_np, other_ge))
        text = changes_text(version, other_version, ranges)
        path = os.path.normpath(os.path.join(root, CHANGES))
        count = sum(hi - lo for lo, hi, _, _ in ranges)
        if args.check:
            current = read(path) if os.path.exists(path) else ""
            if current != text:
                sys.exit(f"error: {CHANGES} is not what the sources of {version} and "
                         f"{other_version} give; regenerate it")
            print(f"{CHANGES} is current ({count} scalar values)")
            return
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {CHANGES}: {count} scalar values in {len(ranges)} ranges")
        return
    path = os.path.join(root, OUTPUT)
    if args.check:
        current = read(path) if os.path.exists(path) else ""
        if current != text:
            sys.exit(f"error: {OUTPUT} is not what the sources of {version} give; regenerate it")
        print(f"{OUTPUT} is current ({len(np)} and {len(ge)} ranges)")
        return
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUTPUT}: {len(np)} ranges not printable, {len(ge)} grapheme-extending")


if __name__ == "__main__":
    main()
