#!/usr/bin/env python3
"""Generate `Dogwood/Frontend/UnicodeTables.lean`: the two Unicode tables Rust's
`char::escape_debug` reads, from the Rust toolchain's own sources.

Rust decides whether `escape_debug` (and `{:?}` of a string or a character) writes a
non-ASCII character as itself or as `\\u{…}` with two sets of code points: the ones it
escapes wherever they are (not printable), and the grapheme extenders, which it escapes when
asked (`char::escape_debug_ext`). Their sources depend on the Rust release:

* up to Rust 1.96, `library/core/src/unicode/printable.rs` (`is_printable`, generated by
  `printable.py`) and the `grapheme_extend` table of `unicode_data.rs`;
* since Rust 1.97, the predicates `escape_debug_ext` tests (`library/core/src/char/methods.rs`:
  `is_control`, `is_private_use`, `is_whitespace`, `is_default_ignorable`, `is_format_control`
  and `is_assigned`, and `is_grapheme_extender`) over the tables of `unicode_data.rs`
  (`white_space`, `default_ignorable_code_point`, `cf`, `cn_planes_0_3`, `grapheme_extend`).

This script decodes them, as the code in those files reads them, into sorted lists of
half-open code point ranges, and writes them as a Lean module. The Lean frontend's escaping
(`Dogwood/Frontend/Escape.lean`) reads them, so that it prints every string, entity id,
pattern and provider argument exactly as the crate does when the crate is built with this
toolchain.

The tables are pinned to one Rust release, `RUST_VERSION`, the toolchain the crate builds
with. The script reads the sources of the active `rustc` (`rustc --print sysroot`, the
`rust-src` component) and refuses another version; `RUSTUP_TOOLCHAIN` selects one.

Usage (from `dogwood-lean/`):

    scripts/gen_unicode_tables.py            write Dogwood/Frontend/UnicodeTables.lean
    scripts/gen_unicode_tables.py --check    fail if the file is not what the sources give
    scripts/gen_unicode_tables.py --verify   also compile and run a Rust program that
                                             escapes every scalar value with the toolchain,
                                             and compare it with the decoded tables
    scripts/gen_unicode_tables.py --changes TOOLCHAIN
                                             write ../dogwood-language/src/lean_frontend/
                                             escape_changes.txt: the scalar values that
                                             RUST_VERSION and the rustup toolchain TOOLCHAIN
                                             escape differently (with --check, check it;
                                             with --self-test and --verify, test both
                                             toolchains' tables)

`--self-test` evaluates the sources' lookup functions (ported literally) on every code point
and compares them with the decoded ranges.

To move to another Rust release: set `RUST_VERSION`, run the script with that toolchain and
`--verify`, and rebuild.

The crate can be compiled with a Rust release other than `RUST_VERSION`, for example during a
toolchain upgrade, and one set of tables cannot match two releases that escape some scalar
values differently. `--changes` lists those scalar values; the crate's test of the tables
leaves them out (and checks that the compiler escapes them as listed) when the compiler is the
other release.

Since Rust 1.99 the fast path of `escape_debug_ext` also prints `U+FF9E` and `U+FF9F` (grapheme
extenders) as themselves; the script reads the fast path's code points from the sources and
leaves them out of both tables.
"""

import argparse
import hashlib
import os
import re
import subprocess
import sys
import tempfile

RUST_VERSION = "1.98.1"
OUTPUT = os.path.join("Dogwood", "Frontend", "UnicodeTables.lean")
MAX_CHAR = 0x110000


def toolchain_env(toolchain):
    """The environment that runs `rustc` of `toolchain` (a rustup toolchain name), or the active
    one when `toolchain` is `None`."""
    env = dict(os.environ)
    if toolchain is not None:
        env["RUSTUP_TOOLCHAIN"] = toolchain
    return env


def rust_sources(toolchain=None, pinned=True):
    """A toolchain's version and its `library/core/src/unicode` directory: the active one, which
    must be `RUST_VERSION`, or with `pinned` false the rustup toolchain `toolchain`."""
    env = toolchain_env(toolchain)
    try:
        version = subprocess.run(["rustc", "--version"], check=True, capture_output=True,
                                 text=True, env=env).stdout.strip()
        sysroot = subprocess.run(["rustc", "--print", "sysroot"], check=True,
                                 capture_output=True, text=True, env=env).stdout.strip()
    except (OSError, subprocess.CalledProcessError) as e:
        sys.exit(f"error: cannot run rustc: {e}")
    m = re.match(r"rustc (\S+)", version)
    if not m:
        sys.exit(f"error: cannot read the release of `{version}`")
    if pinned and m.group(1) != RUST_VERSION:
        sys.exit(f"error: the tables are pinned to Rust {RUST_VERSION}, and the active rustc is "
                 f"`{version}`; select a {RUST_VERSION} toolchain (RUSTUP_TOOLCHAIN), or change "
                 f"RUST_VERSION and regenerate")
    src = os.path.join(sysroot, "lib", "rustlib", "src", "rust", "library", "core", "src",
                       "unicode")
    needed = ["unicode_data.rs"]
    if not os.path.isfile(os.path.join(src, "printable.rs")):
        needed.append(os.path.join("..", "char", "methods.rs"))
    for f in needed:
        if not os.path.isfile(os.path.join(src, f)):
            sys.exit(f"error: no {f} in {src}; install the toolchain's sources "
                     f"(`rustup component add rust-src`)")
    return version, src


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def ints(text):
    """Every integer literal (decimal or hexadecimal) in `text`, in order."""
    return [int(t, 0) for t in re.findall(r"\b(0x[0-9a-fA-F]+|[0-9]+)\b", text)]


def array_body(src, name):
    """The text between the brackets of the array constant or static `name`."""
    m = re.search(r"(?:const|static)\s+" + re.escape(name) + r"\s*:[^=]*=\s*&?\[", src)
    if not m:
        sys.exit(f"error: no array `{name}` in the sources")
    depth, i = 1, m.end()
    while depth:
        c = src[i]
        depth += c == "["
        depth -= c == "]"
        i += 1
    return src[m.end():i - 1]


def normalize(ranges):
    """Sort and merge half-open ranges."""
    out = []
    for lo, hi in sorted(r for r in ranges if r[0] < r[1]):
        if out and lo <= out[-1][1]:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


# ── printable.rs ──────────────────────────────────────────────────────────────


def printable_plane(src, upper_name, lower_name, normal_name, base):
    """The code points of one plane (`base` to `base + 0x10000`) that `check` reports not
    printable: its singletons, and the runs of its `normal` table that end with `current`
    false."""
    uppers = ints(array_body(src, upper_name))
    lowers = ints(array_body(src, lower_name))
    normal = ints(array_body(src, normal_name))
    pairs = list(zip(uppers[0::2], uppers[1::2]))
    ranges = []
    start = 0
    for upper, count in pairs:
        for lower in lowers[start:start + count]:
            x = base + (upper << 8 | lower)
            ranges.append((x, x + 1))
        start += count
    if start != len(lowers):
        sys.exit(f"error: {upper_name} does not cover {lower_name}")
    # `check` walks the run lengths from 0, flipping `current` (initially printable) after
    # each run; the code point is printable iff `current` is true where it stops.
    x, current, i = 0, True, 0
    while i < len(normal):
        v = normal[i]
        i += 1
        if v & 0x80:
            length = (v & 0x7F) << 8 | normal[i]
            i += 1
        else:
            length = v
        if not current:
            ranges.append((base + x, base + x + length))
        x += length
        current = not current
    if not current:
        ranges.append((base + x, base + 0x10000))
    return [(lo, min(hi, base + 0x10000)) for lo, hi in ranges]


def is_printable_tail(src):
    """The ranges `is_printable` rejects above `0x20000`: its `if lo <= x && x < hi`
    tests."""
    m = re.search(r"pub\(crate\) fn is_printable\(x: char\) -> bool \{(.*?)\n\}", src, re.S)
    if not m:
        sys.exit("error: no `is_printable` in printable.rs")
    body = m.group(1)
    tail = body[body.index("} else {"):]
    tests = re.findall(r"if (0x[0-9a-f]+) <= x && x < (0x[0-9a-f]+) \{\s*return false;", tail)
    if not tests or not re.search(r"\btrue\s*\}\s*$", tail.strip()):
        sys.exit("error: `is_printable` is not of the expected form")
    return [(int(lo, 16), int(hi, 16)) for lo, hi in tests]


def non_printable(src):
    """The code points `core::unicode::printable::is_printable` rejects: below `0x20`, then
    from `0x7f` the table of each of the first two planes, then the ranges of the tail."""
    body = re.search(r"pub\(crate\) fn is_printable\(x: char\) -> bool \{(.*?)\n\}", src,
                     re.S).group(1)
    expected = ["if x < 32", "false", "x < 127", "true", "x < 0x10000",
                "check(lower, SINGLETONS0U, SINGLETONS0L, NORMAL0)", "x < 0x20000",
                "check(lower, SINGLETONS1U, SINGLETONS1L, NORMAL1)"]
    pos = 0
    for token in expected:
        pos = body.find(token, pos)
        if pos < 0:
            sys.exit(f"error: `is_printable` is not of the expected form (no `{token}`)")
    plane0 = [(max(lo, 0x7F), hi) for lo, hi in
              printable_plane(src, "SINGLETONS0U", "SINGLETONS0L", "NORMAL0", 0) if hi > 0x7F]
    plane1 = printable_plane(src, "SINGLETONS1U", "SINGLETONS1L", "NORMAL1", 0x10000)
    return normalize([(0, 0x20)] + plane0 + plane1 + is_printable_tail(src))


def check_literal(x, uppers, lowers, normal):
    """`printable.rs`'s `check`, ported literally (for --self-test)."""
    xupper = x >> 8
    lowerstart = 0
    for upper, count in uppers:
        lowerend = lowerstart + count
        if xupper == upper:
            if (x & 0xFF) in lowers[lowerstart:lowerend]:
                return False
        elif xupper < upper:
            break
        lowerstart = lowerend
    x, current, i = x, True, 0
    while i < len(normal):
        v = normal[i]
        i += 1
        if v & 0x80:
            length = (v & 0x7F) << 8 | normal[i]
            i += 1
        else:
            length = v
        x -= length
        if x < 0:
            break
        current = not current
    return current


# ── unicode_data.rs: grapheme_extend ─────────────────────────────────────────


def skiplist_module(src, name, guard):
    """The skip list of the `unicode_data.rs` module `name`, whose `lookup` is
    `(c as u32) >= guard && lookup_slow(c)`."""
    m = re.search(r"pub mod " + name + r" \{(.*?)\n\}", src, re.S)
    if not m:
        sys.exit(f"error: no `{name}` module in unicode_data.rs")
    body = m.group(1)
    if "skip_search(c, &SHORT_OFFSET_RUNS, &OFFSETS)" not in body or \
            f"(c as u32) >= {guard:#x} && lookup_slow(c)" not in body:
        sys.exit(f"error: `{name}` is not a skip list of the expected form")
    headers = [(int(a), int(b)) for a, b in
               re.findall(r"ShortOffsetRunHeader::new\((\d+),\s*(\d+)\)",
                          array_body(body, "SHORT_OFFSET_RUNS"))]
    offsets = ints(array_body(body, "OFFSETS"))
    return headers, offsets


def grapheme_module(src):
    return skiplist_module(src, "grapheme_extend", 0x300)


def skiplist(src, name, guard):
    """The ranges of the `lookup` of the `unicode_data.rs` module `name`, decoded from its skip
    list: the offsets are the differences between consecutive range boundaries, a difference
    too large for a byte being a 0 that closes a run, whose header holds the boundary as a
    prefix sum. The last boundary is beyond `char::MAX`. `lookup` is false below `guard`."""
    headers, offsets = skiplist_module(src, name, guard)
    points, base = [], 0
    for k, (start, prefix_sum) in enumerate(headers):
        end = headers[k + 1][0] if k + 1 < len(headers) else len(offsets)
        run = offsets[start:end]
        for e in run[:-1]:
            base += e
            points.append(base)
        base = prefix_sum
        points.append(base)
    if points[-1] < MAX_CHAR or len(points) % 2 != 1:
        sys.exit(f"error: the {name} skip list does not decode")
    points.pop()
    ranges = list(zip(points[0::2], points[1::2]))
    return normalize([(max(lo, guard), hi) for lo, hi in ranges if hi > guard])


def grapheme_extend(src):
    """The ranges of `grapheme_extend::lookup` (false below `0x300`)."""
    return skiplist(src, "grapheme_extend", 0x300)


# ── Since Rust 1.97: char/methods.rs over unicode_data.rs ────────────────────


def fn_body(src, signature):
    """The body of the function whose declaration contains `signature` (up to its first line
    that closes it at its indentation)."""
    m = re.search(r"\n( *)[^\n]*" + re.escape(signature) + r"[^\n]*\{\n(.*?)\n\1\}", src, re.S)
    if not m:
        sys.exit(f"error: no `{signature}` in the sources")
    return m.group(2)


def expect(body, what, tokens):
    pos = 0
    for token in tokens:
        pos = body.find(token, pos)
        if pos < 0:
            sys.exit(f"error: `{what}` is not of the expected form (no `{token}`)")
        pos += len(token)


def char_ranges(text):
    """The `'…'` and `'…'..='…'` patterns of `text`, as half-open ranges."""
    def code(lit):
        if lit.startswith("\\u{"):
            return int(lit[3:-1], 16)
        if lit.startswith("\\x"):
            return int(lit[2:], 16)
        if lit == "\\0":
            return 0
        return ord(lit)
    lit = r"'(\\u\{[0-9A-Fa-f]+\}|\\x[0-9A-Fa-f]{2}|\\0|[^'\\])'"
    out = []
    for lo, hi in re.findall(lit + r"(?:\.\.=" + lit + r")?", text):
        out.append((code(lo), code(hi or lo) + 1))
    return out


def subtract(ranges, holes):
    """The half-open `ranges` without the code points of `holes`."""
    out = []
    for lo, hi in ranges:
        for a, b in normalize(holes):
            if b <= lo or hi <= a:
                continue
            if lo < a:
                out.append((lo, a))
            lo = max(lo, b)
        if lo < hi:
            out.append((lo, hi))
    return normalize(out)


def escape_debug_ext(methods):
    """Check that `escape_debug_ext` escapes, after its special escapes and its fast path,
    exactly the characters the predicates below decode, and return the code points its fast
    path prints beyond ASCII (since Rust 1.99, `U+FF9E` and `U+FF9F`, grapheme extenders it
    does not escape; none before)."""
    body = fn_body(methods, "fn escape_debug_ext(self, args: EscapeDebugExtArgs)")
    lit = r"'(?:\\u\{[0-9A-Fa-f]+\}|\\x[0-9A-Fa-f]{2}|[^'\\])'"
    fast = re.search(r"'\\x20'\.\.='\\x7E'((?:\s*\|\s*" + lit + r"(?:\.\.=" + lit + r")?)*)"
                     r"\s*=> EscapeDebug::printable\(self\)", body)
    if not fast:
        sys.exit("error: `escape_debug_ext` is not of the expected form (no ASCII fast path)")
    expect(body[fast.end():], "escape_debug_ext", [
        "_ if self.is_control()", "|| self.is_private_use()", "|| self.is_whitespace()",
        "|| args.escape_grapheme_extender && self.is_grapheme_extender()",
        "|| self.is_default_ignorable()", "|| self.is_format_control()",
        "|| !self.is_assigned() =>", "EscapeDebug::unicode(self)",
        "_ => EscapeDebug::printable(self)"])
    return normalize(char_ranges(fast.group(1)))


def white_space(methods, data):
    """`is_whitespace`: its ASCII cases, then `white_space::lookup`'s map and code points."""
    body = fn_body(methods, "pub const fn is_whitespace(self) -> bool")
    expect(body, "is_whitespace", ["' ' | '\\x09'..='\\x0d' => true", "'\\0'..='\\u{84}' => false",
                                   "_ => unicode::White_Space(self)"])
    m = re.search(r"pub mod white_space \{(.*?)\n\}", data, re.S)
    if not m:
        sys.exit("error: no `white_space` module in unicode_data.rs")
    module = m.group(1)
    expect(module, "white_space::lookup", [
        "match c as u32 >> 8 {", "0 => WHITESPACE_MAP[c as usize & 0xff] & 1 != 0",
        "22 => c as u32 == 0x1680", "32 => WHITESPACE_MAP[c as usize & 0xff] & 2 != 0",
        "48 => c as u32 == 0x3000", "_ => false"])
    wmap = ints(array_body(module, "WHITESPACE_MAP"))
    if len(wmap) != 256:
        sys.exit("error: WHITESPACE_MAP is not 256 entries")
    points = [x for x in range(0x85, 0x100) if wmap[x] & 1] + [0x1680] + \
        [0x2000 + x for x in range(256) if wmap[x] & 2] + [0x3000]
    return [(0x09, 0x0E), (0x20, 0x21)] + [(x, x + 1) for x in points]


def guarded(methods, data, predicate, table, module):
    """A predicate `self > '\\u{AC}' && unicode::<table>(self)` over a skip list."""
    body = fn_body(methods, f"fn {predicate}(self) -> bool")
    expect(body, predicate, [f"self > '\\u{{AC}}' && unicode::{table}(self)"])
    return skiplist(data, module, 0xAD)


def unassigned(methods, data):
    """The code points `is_assigned` rejects: those of `cn_planes_0_3::lookup` in its range, and
    beyond it the ones outside its list of assigned ranges."""
    body = fn_body(methods, "pub fn is_assigned(self) -> bool")
    expect(body, "is_assigned", ["'\\0'..='\\u{377}' => true",
                                 "'\\u{378}'..='\\u{3FFFD}' => !unicode::Cn_planes_0_3(self)",
                                 "=> true", "_ => false"])
    head, tail = body.split("!unicode::Cn_planes_0_3(self),", 1)
    assigned = normalize(char_ranges(tail.split("=> true")[0]))
    cn = [(lo, hi) for lo, hi in skiplist(data, "cn_planes_0_3", 0x378) if lo < 0x3FFFE]
    out = [(lo, min(hi, 0x3FFFE)) for lo, hi in cn]
    x = 0x3FFFE
    for lo, hi in assigned:
        if lo < x:
            sys.exit("error: `is_assigned`'s ranges are not beyond plane 3")
        out.append((x, lo))
        x = hi
    out.append((x, MAX_CHAR))
    return out


def non_printable_since_1_97(methods, data):
    """The code points `escape_debug_ext` escapes whatever its arguments (not printable): the
    controls, private-use characters, whitespace, default-ignorable code points, format
    controls and unassigned code points, but none of its fast path (`0x20` to `0x7e`, which
    takes the space before `is_whitespace`, and since Rust 1.99 `U+FF9E` and `U+FF9F`)."""
    fast = escape_debug_ext(methods)
    control = fn_body(methods, "pub const fn is_control(self) -> bool")
    expect(control, "is_control", ["matches!(self, '\\0'..='\\x1f' | '\\x7f'..='\\u{9f}')"])
    private = fn_body(methods, "pub const fn is_private_use(self) -> bool")
    expect(private, "is_private_use", ["matches!(self,"])
    escaped = normalize([(0, 0x20), (0x7F, 0xA0)]
                     + char_ranges(private[private.index("matches!(self,"):])
                     + white_space(methods, data)
                     + guarded(methods, data, "is_default_ignorable",
                               "Default_Ignorable_Code_Point", "default_ignorable_code_point")
                     + guarded(methods, data, "is_format_control", "Cf", "cf")
                     + unassigned(methods, data))
    # The fast path prints `0x20` to `0x7e`, and its other code points, as themselves.
    out = []
    for lo, hi in escaped:
        out += [(a, b) for a, b in [(lo, min(hi, 0x20)), (max(lo, 0x7F), hi)] if a < b]
    return subtract(out, fast)


def skip_search_literal(c, headers, offsets):
    """`unicode_data.rs`'s `skip_search`, ported literally (for --self-test)."""
    keys = [(s << 21 | p) << 11 & 0xFFFFFFFF for s, p in headers]
    needle = (c << 11) & 0xFFFFFFFF
    lo, hi = 0, len(keys)
    found = None
    while lo < hi:
        mid = (lo + hi) // 2
        if keys[mid] < needle:
            lo = mid + 1
        elif keys[mid] > needle:
            hi = mid
        else:
            found = mid
            break
    last_idx = found + 1 if found is not None else lo
    offset_idx = headers[last_idx][0]
    length = (headers[last_idx + 1][0] if last_idx + 1 < len(headers) else len(offsets)) - offset_idx
    prev = headers[last_idx - 1][1] if last_idx > 0 else 0
    total = c - prev
    prefix_sum = 0
    for _ in range(length - 1):
        prefix_sum += offsets[offset_idx]
        if prefix_sum > total:
            break
        offset_idx += 1
    return offset_idx % 2 == 1


